export const getPractice = (id: unknown) => (typeof id === "string" ? PRACTICES.find((p) => p.id === id) : undefined);

// [CATALOG] для системного промпта: компактные карточки.
export function catalogPrompt(withApp = true) {
  return PRACTICES.map((p) => {
    const lines = [
      `${p.id} «${p.title}» (фокус ${p.focus}, ${p.minutes})`,
      `Когда: ${p.when}.`,
      `Ограничения: ${p.stop}.`,
      `Шаги: ${p.steps.map((s, i) => `${i + 1}) ${s}`).join(" ")}`,
      `После: ${p.after}`,
    ];
    if (withApp && p.app) lines.push(`В приложении есть упражнение: [[step:${p.app}]].`);
    return lines.join("\n");
  }).join("\n\n");
}
