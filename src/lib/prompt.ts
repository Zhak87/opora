// Ответ на языке интерфейса, но если человек пишет на другом из трёх языков, отвечаем на его языке.
function languageNote(locale: Locale) {
  return `Язык ответа: отвечай на ${AI_LANGUAGE[locale]} языке, это язык, который человек выбрал в приложении. Если человек сам пишет на другом языке (русском, казахском или английском), отвечай на том языке, на котором он пишет в последнем сообщении. Пиши грамотно и естественно, как носитель этого языка, не переводи дословно с русского. По-казахски пиши только кириллицей с казахскими буквами (ә, ғ, қ, ң, ө, ұ, ү, һ, і), без латинских символов. Все правила выше действуют на любом языке.`;
}

// Подсказка про кнопки упражнений под чатом: есть только в основном чате, не в пробном и не в голосовом режиме.
const CALM_TOOLS =
  "Спокойные игры в приложении: когда человеку тревожно, под чатом появляются кнопки «Подышать» (дыхание вдох 4 — задержка 4 — выдох 6), «Отпустить мысли» (лопать пузырьки с тревожными мыслями) и «5-4-3-2-1» (заземление через органы чувств). Можно предложить нажать одну из них и вернуться в разговор, когда станет немного легче.";

export function buildSystemPrompt(opts: {
  mode: string;
  topic?: string | null;
  name?: string | null;
  locale?: Locale;
  calmTools?: boolean;
  intake?: string | null;
}) {
  const parts = [BASE];
  if (opts.calmTools) parts.push(CALM_TOOLS);
  const topic = getTopic(opts.topic);
  if (topic) parts.push(topic.guidance);
  if (MODES[opts.mode]) parts.push(MODES[opts.mode]);
  if (opts.intake) parts.push(opts.intake);
  if (opts.name) parts.push(`Человека зовут ${opts.name}. Можно иногда обращаться по имени, но не в каждом сообщении.`);
  parts.push(languageNote(opts.locale ?? DEFAULT_LOCALE));
  return parts.join("\n\n");
}

